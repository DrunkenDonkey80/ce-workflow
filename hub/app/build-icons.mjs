// D8: the app draws its icons with the hub's own icons.ts, stripped to plain JS, so tab and app icons never drift.
import { readFileSync, writeFileSync } from "node:fs";
import { stripTypeScriptTypes } from "node:module";

const source = readFileSync(new URL("../web/icons.ts", import.meta.url), "utf8");
const out = new URL("./ui/icons.js", import.meta.url);
writeFileSync(out, "// Generated by hub/app/build-icons.mjs from hub/web/icons.ts; do not edit.\n" + stripTypeScriptTypes(source));
console.log("wrote " + out.pathname);
