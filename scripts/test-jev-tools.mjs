#!/usr/bin/env node
// Canonical offline check: node scripts/test-jev-tools.mjs
import assert from "node:assert/strict";
import { mkdtemp, writeFile, mkdir, rm, symlink } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { captureSource, compactionState, compactionVerdict, createJevTools, jevSettings, jevStatus, runAsk, runEvidence, runTriage, usageTier, validateQuestions } from "../extensions/jev-tools.ts";
const cwd = await mkdtemp(join(tmpdir(), "jev-tools-test-"));
const other = await mkdtemp(join(tmpdir(), "jev-outside-"));
const q = { relevant: { type: "bool", instructions: "Does the supplied evidence concern battery data?", criteria: { true: "Relevant", false: "Unrelated" } } };
const model = { provider: "openrouter", id: "typesafe/jev-1.13", contextWindow: 32000 };
const usage = { input: 10, output: 1, cacheRead: 0, cacheWrite: 0, totalTokens: 11, cost: { input: 0.001, output: 0, cacheRead: 0, cacheWrite: 0, total: 0.001 } };
const calls = [];
const registry = {
	getModelOfType: () => model,
	getProviderAuthStatus: () => ({ configured: true }),
	getApiKeyForProvider: () => { throw new Error("Credential getter must not be called"); },
	async classify(selected, context) {
		calls.push(context);
		return { provider: selected.provider, model: selected.id, stopReason: "stop", usage,
			answers: Object.fromEntries(Object.entries(context.questions).map(([id, question]) => {
				if (question.type === "bool") return [id, { type: "bool", probability: 0.5 }];
				if (question.type === "score") return [id, { type: "score", score: 0.5, confidence: 0.5 }];
				return [id, { type: "choice", choice: "yes", probabilities: { yes: 0.5, no: 0.5 }, confidence: 0.5 }];
			})) };
	},
};
const run = (jobs, options = {}) => runTriage({ jobs, cwd, registry, model, ...options });
try {
	await writeFile(join(cwd, "Battery.kt"), "class Battery {\n val temperature = 24\n}\n");
	await writeFile(join(cwd, "Test.kt"), "assertEquals(24, temperature)\n");
	assert.equal(jevSettings({}).enabled, false);
	assert.equal(jevStatus({}, registry).status, "Off");
	assert.equal(jevStatus({ workOrchestrator: { jev: { enabled: true } } }, {}).status, "Unsupported Pi API");
	assert.equal(jevStatus({ workOrchestrator: { jev: { enabled: true } } }, { ...registry, getProviderAuthStatus: () => ({ configured: false }) }).status, "Enabled but unconfigured");
	const thirty = Object.fromEntries(Array.from({ length: 30 }, (_, i) => [`q${i}`, q.relevant]));
	let result = await run([{ id: "many", questions: thirty, sources: [{ path: "Battery.kt" }] }]);
	assert.equal(calls.length, 1);
	assert.equal(Object.keys(result.results[0].answers).length, 30);
	assert.equal(result.results[0].answers.q0.band, "uncertain");
	assert.equal(result.usage.totalTokens, 11);
	assert.equal(result.results[0].sources[0].startLine, undefined, "whole-file anchors cannot invent matched lines");
	assert(!JSON.stringify(result).includes("val temperature"), "triage does not leak bodies");
	result = await run([{ id: "bundle", questions: q, sources: [{ path: "Battery.kt", startLine: 2, endLine: 2 }, { path: "Test.kt" }] }, { id: "state", questions: q, state: { test: "passed" } }]);
	assert.equal(result.coverage.calls, 2);
	assert.equal(result.results[0].sources[0].startLine, 2);
	assert.equal(calls.find(c => c.state.sources.length === 2).state.sources[0].content, " val temperature = 24");
	const typed = { pick: { type: "choice", instructions: "Pick relevant", criteria: { yes: "relevant", no: "not relevant" } }, score: { type: "score", instructions: "Relevance", criteria: ["none", "some", "all"] } };
	result = await run([{ id: "typed", questions: typed, state: { missing: null } }]);
	assert.equal(result.results[0].answers.pick.choice, "yes");
	assert.equal(result.results[0].answers.score.score, 0.5);
	assert.equal(calls.at(-1).state.data.missing, null);
	const before = calls.length;
	await assert.rejects(run([{ id: "ok", questions: q }, { id: "bad", questions: { q: { type: "extract" } } }]), /question|instructions/);
	await assert.rejects(run([{ id: "same", questions: q }, { id: "same", questions: q }]), /unique/);
	await assert.rejects(run([{ id: "bad", questions: q, sources: [{ path: "../outside" }] }]), /Traversal/);
	await assert.rejects(run([{ id: "bad", questions: q, sources: [{ path: "C:/inside:stream" }] }]), /device/);
	assert.equal(calls.length, before);
	assert.throws(() => validateQuestions({ q: { type: "choice", instructions: "Pick", criteria: { yes: "Only one" } } }), /Choice/);
	for (const [name, body] of [[".env.local", "safe"], ["secret.txt", `api_key = "sk-${"a".repeat(30)}"`], ["binary.txt", "a\0b"], ["large.txt", "x".repeat(270000)]]) {
		await writeFile(join(cwd, name), body);
		await assert.rejects(captureSource(cwd, { path: name }));
	}
	await writeFile(join(other, "outside.txt"), "not allowed");
	await symlink(other, join(cwd, "escape"), "junction");
	await assert.rejects(captureSource(cwd, { path: "escape/outside.txt" }), /outside/);
	await mkdir(join(cwd, "nested"));
	await writeFile(join(cwd, "nested", "a.txt"), "hello");
	assert.equal((await captureSource(cwd, { path: "nested\\a.txt" })).content, "hello");
	result = await run([{ id: "missing", questions: q, sources: [{ path: "absent.kt" }] }]);
	assert.equal(result.coverage.calls, 0);
	assert.equal(result.coverage.incomplete, true);
	const failing = { ...registry, classify: async () => ({ ...model, model: model.id, stopReason: "error", usage, errorMessage: "DO NOT LEAK PROVIDER BODY" }) };
	result = await run([{ id: "failed", questions: q }], { registry: failing });
	assert.equal(result.usage.totalTokens, 11);
	assert.equal(result.results[0].status, "error");
	assert(!JSON.stringify(result).includes("PROVIDER BODY"));
	result = await run([{ id: "malformed", questions: q }], { registry: { ...registry, classify: async () => ({ provider: model.provider, model: model.id, stopReason: "stop", answers: { relevant: { type: "bool", probability: 2 } } }) } });
	assert.equal(result.results[0].status, "error");
	assert.equal(result.coverage.unknownUsageCalls, 1);
	const stopped = new AbortController(); stopped.abort();
	result = await run([{ id: "cancel", questions: q }], { signal: stopped.signal });
	assert.equal(result.coverage.calls, 0);
	let project = {};
	const tools = new Map(), hooks = new Map();
	const pi = { registerTool: tool => tools.set(tool.name, tool), on: (event, handler) => hooks.set(event, handler) };
	const extension = createJevTools(pi, () => project);
	const ctx = { cwd, modelRegistry: registry };
	extension.refresh(ctx);
	assert.equal(tools.size, 0, "default off registers nothing");
	project = { workOrchestrator: { jev: { enabled: true } } }; extension.refresh();
	const tool = tools.get("jev_triage");
	assert.equal(tool.exposure, "direct");
	const direct = await tool.execute("call", { jobs: [{ id: "json", questions: q, state: { status: "test passed" } }] }, undefined, undefined, ctx);
	assert.equal(direct.usage.totalTokens, 11);
	assert.equal(direct.structuredContent.results[0].status, "ok");
	assert.equal(direct.details.usage, undefined, "usage carried exactly once at tool-result top level");
	project = {}; extension.refresh();
	assert.equal(tools.get("jev_triage").exposure, "hidden");
	await assert.rejects(tool.execute("call", { jobs: [{ id: "blocked", questions: q }] }, undefined, undefined, ctx), /off/);
	project = { workOrchestrator: { jev: { enabled: true } } };
	let started;
	const began = new Promise(resolve => { started = resolve; });
	ctx.modelRegistry = { ...registry, classify: () => { started(); return new Promise(() => {}); } };
	extension.refresh(ctx);
	const pending = tool.execute("cancel", { jobs: Array.from({ length: 8 }, (_, i) => ({ id: `job${i}`, questions: q })) }, undefined, undefined, ctx);
	await began; project = {}; extension.refresh();
	const cancelled = await pending;
	assert.equal(cancelled.structuredContent.coverage.calls, 4);
	assert.equal(cancelled.structuredContent.coverage.incomplete, true);
	assert.equal(cancelled.structuredContent.coverage.unknownUsageCalls, 4);
	const evidence = args => runEvidence({ args, cwd, registry, model });
	let selected = await evidence({ scopes: ["*.kt"], unit: "window", pattern: "temperature", questions: q });
	assert.equal(selected.coverage.calls, 2);
	assert.equal(selected.results.length, 2);
	assert(selected.results.every(row => row.startLine >= 1 && row.excerpt.includes("temperature") && row.sha256.length === 64 && !("absolutePath" in row)));
	const boolQuestion = Object.keys(q).find(id => q[id].type === "bool");
	if (boolQuestion) {
		const byTrue = await evidence({ scopes: ["*.kt"], unit: "window", pattern: "temperature", questions: q, rankQuestion: boolQuestion, rankChoice: "true" });
		const byFalse = await evidence({ scopes: ["*.kt"], unit: "window", pattern: "temperature", questions: q, rankQuestion: boolQuestion, rankChoice: "false" });
		assert(byTrue.results.every((row, i) => Math.abs(row.rank + byFalse.results.find(other => other.id === row.id).rank - 1) < 1e-9 && i >= 0), "bool rankChoice true/false are complementary");
	}
	await assert.rejects(evidence({ scopes: ["*.kt"], unit: "window", pattern: "temperature", questions: q, rankChoice: "maybe" }), /ranking choice/);
	selected = await evidence({ scopes: ["*.kt"], unit: "file", pattern: "not present" });
	assert.equal(selected.results.length, 0);
	assert.equal(selected.coverage.incomplete, false);
	assert.equal(selected.coverage.calls, 0);
	selected = await evidence({ scopes: ["Battery.kt"], unit: "file", pattern: ".*" });
	assert.equal(selected.results.length, 0, "literal is the default");
	await assert.rejects(evidence({ scopes: ["*.kt"], unit: "window", pattern: "[", regex: true }), /regex/);
	await assert.rejects(runEvidence({ args: { scopes: ["*.kt"], unit: "file" }, cwd, registry, model, search: async () => ({ error: "rg unavailable" }) }), /rg unavailable/);
	await assert.rejects(evidence({ scopes: ["../*"], unit: "file" }), /Traversal/);
	selected = await runEvidence({ args: { scopes: ["*.kt"], unit: "file", questions: q }, cwd, registry: failing, model });
	assert.equal(selected.results.length, 0);
	assert.equal(selected.failures.length, 2);
	assert.equal(selected.coverage.incomplete, true);
	await mkdir(join(cwd, ".git"));
	await writeFile(join(cwd, ".gitignore"), "ignored.kt\n");
	await writeFile(join(cwd, "ignored.kt"), "temperature");
	selected = await evidence({ scopes: ["*.kt"], unit: "window", pattern: "temperature" });
	assert(!selected.results.some(row => row.path === "ignored.kt"));
	for (let i = 0; i < 40; i++) await writeFile(join(cwd, `candidate${i}.kt`), `temperature ${i}\n${"plain text\n".repeat(1000)}`);
	selected = await evidence({ scopes: ["candidate*.kt"], unit: "file", questions: q });
	assert.equal(selected.coverage.calls, 32);
	assert.equal(selected.coverage.candidateOmissions, 8);
	assert.equal(selected.coverage.incomplete, true);
	assert(Buffer.byteLength(JSON.stringify(selected)) <= 24000);
	assert(selected.results.length <= 10);
	selected = await evidence({ scopes: ["*.txt"], unit: "file" });
	assert(selected.skipped.length >= 3);
	assert.equal(selected.coverage.incomplete, true);
	// jev_ask: command output reaches Jev only; bash failures are errors, not answers.
	const askCalls = calls.length;
	const bashCalls = [];
	const outcome = (exit, output) => ({ isError: exit !== 0, result: { content: [{ type: "text", text: `${output}\nCommand exited with code ${exit}` }], structuredContent: { output, truncated: false, exit_code: exit, wall_time_seconds: 1 } } });
	const askCtx = { cwd, modelRegistry: registry, executeTool: async (name, args) => { bashCalls.push([name, args]); return outcome(1, "FAIL test/battery.test.js SECRET_TEST_OUTPUT_MARKER"); } };
	project = { workOrchestrator: { jev: { enabled: true } } }; extension.refresh(askCtx);
	assert.equal(tools.get("jev_ask"), undefined, "jev_ask is off by default (files only)");
	const askTools = new Map();
	createJevTools({ registerTool: t => askTools.set(t.name, t), on() {} }, () => project, undefined, { ask: true }).refresh(askCtx);
	const ask = askTools.get("jev_ask");
	assert.equal(ask.exposure, "direct");
	let asked = await ask.execute("ask", { questions: q, state: { goal: "fix failing test" }, paths: ["Battery.kt"], command: "npm test" }, undefined, undefined, askCtx);
	assert.deepEqual(bashCalls[0], ["bash", { command: "npm test", timeout: 60 }], "commands go through Pi's bash tool");
	assert.equal(calls.length, askCalls + 1, "one classifier call per situation");
	assert.equal(calls.at(-1).state.output.output, "FAIL test/battery.test.js SECRET_TEST_OUTPUT_MARKER");
	assert.equal(calls.at(-1).state.output.exit_code, 1);
	assert(calls.at(-1).state.files["Battery.kt"].includes("temperature"));
	assert(!JSON.stringify(asked.content).includes("SECRET_TEST_OUTPUT_MARKER") && !JSON.stringify(asked.details).includes("val temperature"), "output/file bodies never return to the model");
	assert.equal(asked.structuredContent.output.exitCode, 1);
	assert.equal(asked.usage.totalTokens, 11);
	assert.equal(asked.details.usage, undefined);
	const blockedCtx = { ...askCtx, executeTool: async () => ({ isError: true, result: { content: [{ type: "text", text: "Blocked by permission rule" }] } }) };
	const beforeBlocked = calls.length;
	await assert.rejects(ask.execute("ask", { questions: q, command: "rm -rf x" }, undefined, undefined, blockedCtx), /did not complete.*Blocked/);
	await assert.rejects(ask.execute("ask", { questions: q, command: "npm test" }, undefined, undefined, { cwd, modelRegistry: registry }), /executeTool/);
	assert.equal(calls.length, beforeBlocked, "no classifier call when the command did not run");
	const huge = { ...askCtx, executeTool: async () => outcome(1, "x".repeat(90000)) };
	await assert.rejects(ask.execute("ask", { questions: q, state: "s", command: "npm test" }, undefined, undefined, huge), /Split into calls:.*output.*too big alone/);
	await assert.rejects(runAsk({ args: { questions: q, paths: ["../outside"] }, cwd, registry, model }), /Traversal/);
	await assert.rejects(runAsk({ args: { questions: q, state: "x".repeat(9000) }, cwd, registry, model }), /8000/);
	await assert.rejects(runAsk({ args: { questions: q }, cwd, registry, model }), /Supply state/);
	await assert.rejects(runAsk({ args: { questions: q, command: "cat .env" }, cwd, registry, model, runCommand: async () => ({ exitCode: 0, output: `api_key = "sk-${"a".repeat(30)}"` }) }), /secrets/);
	asked = await runAsk({ args: { questions: q, state: "s" }, cwd, registry: failing, model });
	assert.match(asked.error, /Classifier failed/);
	assert.equal(asked.usage.totalTokens, 11);
	// Compaction note: warning-only, chat entry never sent to the model.
	assert.deepEqual([usageTier(49), usageTier(50), usageTier(70), usageTier(85)], [undefined, "notice", "recommend", "request"]);
	const b = probability => ({ type: "bool", probability });
	assert.equal(compactionVerdict({ mid_operation: b(0.9), switched_gears: b(0.99), at_boundary: b(0.9), needs_history: { score: 0 } }).show, false);
	assert.equal(compactionVerdict({ mid_operation: b(0.1), switched_gears: b(0.8), at_boundary: b(0.1), needs_history: { score: 2 } }).show, true);
	assert.equal(compactionVerdict({ mid_operation: b(0.1), switched_gears: b(0.1), at_boundary: b(0.9), needs_history: { score: 0.5 } }).show, true);
	assert.equal(compactionVerdict({ mid_operation: b(0.1), switched_gears: b(0.1), at_boundary: b(0.9), needs_history: { score: 1.5 } }).show, false);
	const branch = [{ type: "message", message: { role: "user", content: "fix battery" } }, { type: "compaction", summary: "did battery" }, { type: "message", message: { role: "user", content: [{ type: "text", text: "now docs" }] } }];
	const built = compactionState(branch, { role: "assistant", content: [{ type: "text", text: "Done." }] }, [{ toolName: "read" }]);
	assert.deepEqual(built, { current_request: "now docs", previous_work: "Summary: did battery\n---\nfix battery", recent_turn: "Done.", tools_this_turn: ["read"] });
	const entries = [], renderers = new Map(), noteHooks = new Map();
	const notePi = { registerTool() {}, on: (event, handler) => noteHooks.set(event, handler), appendEntry: (type, data) => entries.push([type, data]), registerEntryRenderer: (type, render) => renderers.set(type, render) };
	let noteProject = { workOrchestrator: { jev: { enabled: true } } };
	const notes = createJevTools(notePi, () => noteProject);
	let percent = 60;
	const switched = { ...registry, classify: async (selected, context) => { calls.push(context); return { provider: selected.provider, model: selected.id, stopReason: "stop", usage, answers: { switched_gears: b(0.9), at_boundary: b(0.2), needs_history: { type: "score", score: 1, confidence: 0.8 }, mid_operation: b(0.1) } }; } };
	const noteCtx = { cwd, modelRegistry: switched, getContextUsage: () => ({ percent, tokens: 1, contextWindow: 2 }), sessionManager: { getBranch: () => branch } };
	const turn = async () => { noteHooks.get("turn_end")({ message: { role: "assistant", content: "ok" }, toolResults: [] }, noteCtx); await notes.pendingAdvice(); };
	const beforeNote = calls.length;
	await turn();
	assert.equal(calls.length, beforeNote, "toggle off: no classifier call");
	noteProject = { workOrchestrator: { jev: { enabled: true, compactionNote: true } } };
	percent = 40; await turn();
	assert.equal(calls.length, beforeNote, "below 50%: no classifier call");
	noteHooks.get("agent_start")();
	percent = 60; await turn();
	assert.equal(calls.length, beforeNote + 1);
	assert.equal(entries.length, 1);
	assert.equal(entries[0][0], "jev-compaction-note");
	assert.equal(entries[0][1].show, true);
	assert.equal(entries[0][1].tier, "notice");
	assert.match(renderers.get("jev-compaction-note")({ data: entries[0][1] }).render(200).join(""), /Consider compacting.*60%.*task changed/);
	await turn();
	assert.equal(calls.length, beforeNote + 1, "same tier is not re-asked in the same run");
	percent = 75; await turn();
	assert.equal(entries.at(-1)[1].tier, "recommend");
	assert.equal(renderers.get("jev-compaction-note")({ data: { ...entries[0][1], show: false } }), undefined, "silent decisions are logged, not shown");
	assert(!("sendMessage" in notePi), "never enters model context");
	console.log("ok - Jev opt-in, guards, native shapes/usage, sources, limits, privacy, failure, cancellation, evidence, jev_ask and compaction note");
} finally {
	await rm(cwd, { recursive: true, force: true });
	await rm(other, { recursive: true, force: true });
}
